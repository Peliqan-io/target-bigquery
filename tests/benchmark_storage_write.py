#!/usr/bin/env python3
"""Storage Write API benchmark harness — generate, load, verify, report.

Runs the three PQ-3616 benchmark scenarios end-to-end against a real BigQuery
dataset and prints a report. No prior context needed: records are generated by
the gen_* modules in this directory, piped through the actual target, timed,
and the row counts are verified in BigQuery afterwards.

Scenarios
    exact      realistic Exact Online transaction lines (~0.9 KB/row, 26 cols)
               -> expects NO request splitting (batches fit under 19.5 MB)
    wide       the upstream benchmark shape: 150 columns (~1.7 KB/row)
               -> expects EVERY batch to split into 2 AppendRows requests
    documents  small rows + big documents (up to 18 MB) + oversized (25 MB)
               -> expects splitting AND the >19.5 MB Load Job fallback
    multitable 10 tables in one sync, records interleaved round-robin
               (--rows is PER TABLE; --rows 1000000 = the full 10 x 1M run)
               -> one worker, 10 open AppendRows streams, per-table verification

Usage (from the repo root, inside the poetry env):

    poetry run python tests/benchmark_storage_write.py --config my_config.json
    poetry run python tests/benchmark_storage_write.py --config my_config.json \
        --scenario wide --rows 1000000          # full upstream-comparable run

The config is a normal target-bigquery config (project/credentials_json/dataset/
denormalized). The harness forces the Peliqan runtime profile on top of it:
method=storage_write_api, batch_size=20000, max_workers=1, max_jobs_queued=1.

Default row counts keep the whole suite under ~5 minutes; use --rows to scale
(applies to exact and wide; documents is sized by its doc mix).

Sample report:

    scenario    rows      MB     time    rows/min    MB/min  requests  splits  fallback  bq_delta  result
    exact       200,000   170    62.1s   193,246     164     10        0       0         200,000   PASS
    wide        100,000   167    81.4s   73,710      123     10        5       0         100,000   PASS
    documents   2,020     136    97.0s   1,249       84      9         3       1         2,020     PASS

Tables are created as <table_name_prefix><stream> in the configured dataset and
are left in place for inspection (row counts are measured as before/after deltas,
so re-runs are fine).
"""
import argparse
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

TESTS_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(TESTS_DIR))

import gen_document_sizes  # noqa: E402
import gen_exact_online  # noqa: E402
import gen_throughput_150key  # noqa: E402

TICKET_MIN_ROWS_PER_MIN = 10_000  # PQ-3616 requirement (regular-row scenarios)


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #

def bq_client(cfg):
    from google.cloud import bigquery
    from google.oauth2 import service_account

    creds = service_account.Credentials.from_service_account_info(
        json.loads(cfg["credentials_json"])
    )
    return bigquery.Client(project=cfg["project"], credentials=creds)


def table_count(client, cfg, stream: str):
    table = f"{cfg.get('dataset')}.{cfg.get('table_name_prefix', '')}{stream}"
    try:
        rows = client.query(f"SELECT COUNT(*) AS n FROM `{table}`").result()
        return list(rows)[0].n
    except Exception:
        return 0  # table doesn't exist yet


def run_target(config_path: Path, fixture: Path, log: Path) -> float:
    """Pipe the fixture through target-bigquery; return wall seconds."""
    exe = shutil.which("target-bigquery")
    if exe is None:
        sys.exit("target-bigquery not on PATH — run inside `poetry run` / the venv")
    t0 = time.time()
    with open(fixture, "rb") as fin, open(log, "w") as flog:
        proc = subprocess.run([exe, "--config", str(config_path)],
                              stdin=fin, stdout=flog, stderr=subprocess.STDOUT)
    elapsed = time.time() - t0
    if proc.returncode != 0:
        sys.exit(f"target exited {proc.returncode} — see {log}")
    return elapsed


def parse_log(log: Path):
    text = log.read_text()
    return {
        "requests": text.count("] Sent request "),
        "splits": text.count("; splitting into "),
        "fallback": text.count("diverting to Load Job fallback"),
    }


# --------------------------------------------------------------------------- #
# scenarios: each generates a fixture and returns (stream_name, expectations)
# --------------------------------------------------------------------------- #

def make_exact(workdir: Path, rows: int):
    fixture = workdir / "exact.jsonl"
    with open(fixture, "w") as fh:
        gen_exact_online.gen(rows, fh)
    return fixture, gen_exact_online.STREAM, {"splits": ("==", 0), "fallback": ("==", 0)}


def make_wide(workdir: Path, rows: int):
    fixture = workdir / "wide.jsonl"
    with open(fixture, "w") as fh:
        gen_throughput_150key.gen(rows, fh)
    # 20k rows x ~1.1 KB proto ≈ 22 MB per batch -> every FULL batch must split.
    # Below one full batch (rows < batch_size) the whole run fits one request,
    # so no split is the correct outcome — expect accordingly.
    splits_expect = (">=", 1) if rows >= 20_000 else ("==", 0)
    return fixture, gen_throughput_150key.STREAM, {"splits": splits_expect, "fallback": ("==", 0)}


def make_documents(workdir: Path, rows: int):
    _ = rows  # sized by its doc mix, not --rows
    fixture = workdir / "documents.jsonl"
    gen_document_sizes.main(str(fixture), 2000, 20)  # 2000 small + 20 docs (1 oversized)
    return fixture, "documents", {"splits": (">=", 1), "fallback": (">=", 1)}


MULTITABLE_STREAMS = 10


def make_multitable(workdir: Path, rows: int):
    """10 tables loaded in one sync, records interleaved round-robin — the
    harshest stream-switching pattern: one worker holds an open AppendRows
    stream per table and batches from different tables land back-to-back.
    `rows` is PER TABLE (use --rows 1000000 for the full 10 x 1M run)."""
    fixture = workdir / "multitable.jsonl"
    with open(fixture, "w") as fh:
        gen_exact_online.gen(rows, fh, num_streams=MULTITABLE_STREAMS)
    streams = gen_exact_online.stream_names(MULTITABLE_STREAMS)
    return fixture, streams, {"splits": ("==", 0), "fallback": ("==", 0)}


SCENARIOS = {
    "exact": make_exact,
    "wide": make_wide,
    "documents": make_documents,
    "multitable": make_multitable,
}
DEFAULT_ROWS = {"exact": 200_000, "wide": 100_000, "documents": 0, "multitable": 50_000}


# --------------------------------------------------------------------------- #

def check(expect, metrics):
    for key, (op, want) in expect.items():
        got = metrics[key]
        if op == "==" and got != want:
            return f"FAIL ({key}={got}, expected {want})"
        if op == ">=" and got < want:
            return f"FAIL ({key}={got}, expected >={want})"
    return "PASS"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", required=True, help="target-bigquery config JSON")
    ap.add_argument("--scenario", choices=[*SCENARIOS, "all"], default="all")
    ap.add_argument("--rows", type=int, default=None,
                    help="row count for exact/wide (defaults: 200k / 100k)")
    args = ap.parse_args()

    cfg = json.loads(Path(args.config).read_text())
    cfg.update({"method": "storage_write_api", "batch_size": 20_000})
    cfg.setdefault("options", {}).update({"max_workers": 1, "max_jobs_queued": 1})

    workdir = TESTS_DIR / "local_fixtures"
    workdir.mkdir(exist_ok=True)
    bench_config = workdir / "_bench_config.json"
    bench_config.write_text(json.dumps(cfg))

    client = bq_client(cfg)
    todo = list(SCENARIOS) if args.scenario == "all" else [args.scenario]
    results = []

    for name in todo:
        rows = args.rows or DEFAULT_ROWS[name]
        print(f"\n=== {name}: generating fixture ...", flush=True)
        fixture, stream, expect = SCENARIOS[name](workdir, rows)
        streams = [stream] if isinstance(stream, str) else stream
        size_mb = fixture.stat().st_size / 1024 / 1024
        n_records = sum(1 for line in open(fixture) if '"type": "RECORD"' in line
                        or '"type":"RECORD"' in line)
        before = {s: table_count(client, cfg, s) for s in streams}

        log = workdir / f"_bench_{name}.log"
        print(f"=== {name}: loading {n_records:,} records ({size_mb:.0f} MB) "
              f"through target-bigquery ({len(streams)} table(s)) ...", flush=True)
        elapsed = run_target(bench_config, fixture, log)

        metrics = parse_log(log)
        deltas = {s: table_count(client, cfg, s) - before[s] for s in streams}
        delta = sum(deltas.values())
        verdict = check(expect, metrics)
        per_table = n_records // len(streams)
        bad_tables = {s: d for s, d in deltas.items() if d != per_table}
        if bad_tables:
            verdict = f"FAIL (per-table deltas off: {bad_tables})"
        elif delta != n_records:
            verdict = f"FAIL (bq_delta={delta:,}, expected {n_records:,})"
        if name != "documents" and (n_records / elapsed) * 60 < TICKET_MIN_ROWS_PER_MIN:
            verdict = f"FAIL (below {TICKET_MIN_ROWS_PER_MIN:,} rows/min ticket target)"

        results.append({
            "scenario": name, "rows": n_records, "MB": round(size_mb),
            "time": f"{elapsed:.1f}s",
            "rows/min": f"{n_records / elapsed * 60:,.0f}",
            "MB/min": f"{size_mb / elapsed * 60:,.0f}",
            "requests": metrics["requests"], "splits": metrics["splits"],
            "fallback": metrics["fallback"], "bq_delta": f"{delta:,}",
            "result": verdict,
        })
        print(f"=== {name}: {verdict} · {elapsed:.1f}s · log: {log}")

    cols = list(results[0].keys())
    widths = {c: max(len(c), *(len(str(r[c])) for r in results)) for c in cols}
    print("\n" + "  ".join(c.ljust(widths[c]) for c in cols))
    for r in results:
        print("  ".join(str(r[c]).ljust(widths[c]) for c in cols))
    print("\nProfile: storage_write_api · batch_size=20000 · 1 worker · 1 queued batch"
          f"\nTicket target: {TICKET_MIN_ROWS_PER_MIN:,}+ rows/min (regular rows)."
          "\nTables were appended in the configured dataset; safe to re-run (deltas).")

    if any("FAIL" in r["result"] for r in results):
        sys.exit(1)


if __name__ == "__main__":
    main()
